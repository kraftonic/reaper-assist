import type { Mod, MouseMod, ProfileScript, Shortcut, Workflow } from "../types";
import { reaperColors } from "../skins";

/**
 * Ableton Live (Arrangement View). Look: Live 9's classic light grey (values measured from
 * Live's own skin and screenshots). Keys and mouse: Live 11/12 on macOS (Live uses other
 * modifiers on Windows for copy / velocity drags; REAPER's mouse map can't tell the platforms apart).
 * Action ids checked against REAPER 7.82's action list; mouse ids read back in REAPER 7.82.
 */

const RS = (name: string) => `_RS_assist_ableton_${name}` as const;
const script = (name: string, file: string, label: string, section?: "midi"): ProfileScript => ({
  id: `RS_assist_ableton_${name}`, file: `ableton_${file}.lua`, name: `Live: ${label}`, ...(section ? { section } : {}),
});
const k = (mods: Mod[], key: string, action: Shortcut["action"], does: string): Shortcut => ({ mods, key, action, does });
const m = (mods: Mod[], key: string, action: Shortcut["action"], does: string): Shortcut => ({ mods, key, action, does, section: "midi" });
/** Keys that act on the whole set: from the clip editor they go on to the main window. */
const pass = (mods: Mod[], key: string, does: string): Shortcut => m(mods, key, 40401, `${does} (from the clip editor too)`);
const mouse = (ctx: string, mods: Mod[], value: string, does: string): MouseMod => ({ ctx, mods, value, does });

